// Pages returns a fresh copy of every page.
func Pages() map[byte][]byte {
	out := make(map[byte][]byte, len(pagesHex))
	for page, h := range pagesHex {
		b, err := hex.DecodeString(h)
		if err != nil {
			panic(err)
		}
		out[page] = b
	}
	return out
}
